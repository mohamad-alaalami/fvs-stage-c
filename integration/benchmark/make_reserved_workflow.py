"""Generate .github/workflows/integration-reserved.yml (three static 130-job matrices; written by script to avoid
hand-copying the job definition three times). Usage: python integration/benchmark/make_reserved_workflow.py"""
import json, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
MAN = json.loads((ROOT / 'integration/benchmark/MANIFEST.json').read_text())
IDX = '[' + ', '.join(str(i) for i in range(MAN['graphs'])) + ']'
TIMEOUT = MAN['job_timeout_minutes']

HEAD = r"""name: Integration v1 RESERVED benchmark

# The final benchmark on the 130 reserved graphs. workflow_dispatch ONLY: no push, schedule or other event can
# start it, and the public validation workflow never references it. Dispatch requires the owner's approval token
# for the committed manifest (integration/benchmark/MANIFEST.json) and a passing public validation run of the
# same commit whose recorded build is reused. See integration/PROTOCOL.md. Generated by
# integration/benchmark/make_reserved_workflow.py.
on:
  workflow_dispatch:
    inputs:
      approval:
        description: 'APPROVE-<first 16 hex of SHA-256 of integration/benchmark/MANIFEST.json>'
        required: true
        type: string
      validation_run:
        description: 'Run ID of a passing "Integration v1 public validation" run of this same commit'
        required: true
        type: string

permissions:
  contents: write

concurrency:
  group: integration-v1-reserved
  cancel-in-progress: false

env:
  MSYS_NO_PATHCONV: '1'
  UPSTREAM_URL: https://github.com/karek/FeedbackVertexSet-Experiments
  UPSTREAM_COMMIT: c0290698f6dfcc48b19b55e1aa915d8ecf61b0a4
  OMP_NUM_THREADS: '1'
  OPENBLAS_NUM_THREADS: '1'
  MKL_NUM_THREADS: '1'
  PYTHONHASHSEED: '0'
  PYTHONUNBUFFERED: '1'

jobs:
  guard:
    runs-on: ubuntu-24.04
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-python@v5
        with: { python-version: '3.12' }
      - uses: actions/checkout@v4
        with: { ref: integration-results, path: results, sparse-checkout: 'runs/${{ inputs.validation_run }}' }
      - name: Owner approval, research branch, validated build of this commit
        env: { APPROVAL: '${{ inputs.approval }}', VRUN: '${{ inputs.validation_run }}' }
        run: |
          set -euo pipefail
          want="APPROVE-$(sha256sum integration/benchmark/MANIFEST.json | cut -c1-16)"
          test "$APPROVAL" = "$want" || { echo "approval token does not match the committed manifest"; exit 1; }
          test "$GITHUB_REF_NAME" = integration-v1-20261124
          python integration/benchmark/guard.py "results/runs/$VRUN" "$GITHUB_SHA"

  schedule:
    needs: guard
    runs-on: ubuntu-24.04
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-python@v5
        with: { python-version: '3.12' }
      - uses: actions/checkout@v4
        with: { ref: integration-results, path: results, sparse-checkout: README.md, sparse-checkout-cone-mode: false }
      - name: List reserved graph IDs (names only, no file contents) and apply the fixed schedule rule
        run: |
          set -euo pipefail
          git clone -q --filter=blob:none --no-checkout "$UPSTREAM_URL" upstream
          git -C upstream ls-tree --name-only "$UPSTREAM_COMMIT" tests/pace16-hidden/ | python integration/benchmark/ids.py > ids.txt
          mkdir -p sched && python integration/schedule.py --graph-ids ids.txt --out sched/schedule.json --cpu-limit 1800 --expect 130 > sched/schedule.log
          cp integration/benchmark/MANIFEST.json sched/
          bash integration/publish.sh "$PWD/sched" "runs/${GITHUB_RUN_ID}/schedule/attempt-${GITHUB_RUN_ATTEMPT}" "integration-v1 reserved schedule ${GITHUB_RUN_ID}"
      - uses: actions/upload-artifact@v4
        with: { name: 'reserved-schedule', path: sched/, retention-days: 90 }
"""

BENCH = r"""
  bench-SOLVER:
    needs: [guard, schedule]
    runs-on: windows-2025
    timeout-minutes: TIMEOUT
    strategy:
      fail-fast: false
      max-parallel: PAR
      matrix:
        index: IDX
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-python@v5
        with: { python-version: '3.12' }
      - name: Validated build (hash-checked again by bench.py)
        uses: actions/checkout@v4
        with: { ref: integration-results, path: validated, sparse-checkout: 'runs/${{ inputs.validation_run }}/build/attempt-1' }
      - uses: actions/checkout@v4
        with: { ref: integration-results, path: results, sparse-checkout: README.md, sparse-checkout-cone-mode: false }
      - uses: actions/download-artifact@v4
        with: { name: 'reserved-schedule', path: sched }
      - name: This job's reserved graph only
        id: g
        shell: bash
        run: |
          set -euo pipefail
          g=$(python -c "import json;print(json.load(open('sched/schedule.json'))['jobs']['SOLVER'][${{ matrix.index }}]['graph_id'])")
          echo "graph=$g" >> "$GITHUB_OUTPUT"
          git clone -q --filter=blob:none --no-checkout "$UPSTREAM_URL" upstream
          cd upstream && git sparse-checkout set --no-cone "/tests/pace16-hidden/$g.graph" && git checkout -q --detach "$UPSTREAM_COMMIT"
          test "$(ls tests/pace16-hidden | wc -l)" = 1
      - name: Benchmark job (baseline, linear, boost sequentially in the scheduled order)
        run: python integration/bench.py --reserved --build validated/runs/${{ inputs.validation_run }}/build/attempt-1 --schedule sched/schedule.json --solver SOLVER --index ${{ matrix.index }} --graph-dir upstream/tests/pace16-hidden --out job
      - name: Publish job record (new attempt directory; no force)
        id: pub
        if: always()
        shell: bash
        run: |
          if [ -d job ]; then bash integration/publish.sh "$PWD/job" "runs/${GITHUB_RUN_ID}/jobs/SOLVER/${{ steps.g.outputs.graph }}/attempt-${GITHUB_RUN_ATTEMPT}" "integration-v1 reserved ${GITHUB_RUN_ID} SOLVER/${{ steps.g.outputs.graph }} attempt ${GITHUB_RUN_ATTEMPT}"; fi
      - name: Fallback record if publishing failed (infrastructure; the job is retried)
        if: failure() && steps.pub.outcome == 'failure'
        uses: actions/upload-artifact@v4
        with: { name: 'unpublished-SOLVER-${{ matrix.index }}-a${{ github.run_attempt }}', path: job/, retention-days: 90 }
"""

TAIL = r"""
  report:
    needs: [bench-8, bench-5, bench-LP]
    if: always()
    runs-on: ubuntu-24.04
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-python@v5
        with: { python-version: '3.12' }
      - uses: actions/download-artifact@v4
        with: { name: 'reserved-schedule', path: sched }
      - uses: actions/checkout@v4
        with: { ref: integration-results, path: results, sparse-checkout: 'runs/${{ github.run_id }}/jobs' }
      - run: |
          set -euo pipefail
          python integration/report.py --schedule sched/schedule.json --jobs results/runs/${{ github.run_id }}/jobs --out out/report --title 'Integration-v1 reserved benchmark'
          cat out/report/REPORT.md >> "$GITHUB_STEP_SUMMARY"
          bash integration/publish.sh "$PWD/out/report" "runs/${GITHUB_RUN_ID}/report/attempt-${GITHUB_RUN_ATTEMPT}" "integration-v1 reserved report ${GITHUB_RUN_ID} attempt ${GITHUB_RUN_ATTEMPT}"
"""

body = HEAD
for s in ('8', '5', 'LP'):
    body += BENCH.replace('SOLVER', s).replace('TIMEOUT', str(TIMEOUT)).replace('PAR', str(MAN['max_parallel_per_matrix'][s])).replace('IDX', IDX)
body += TAIL
(ROOT / '.github/workflows/integration-reserved.yml').write_bytes(body.encode())
print('written', len(body))
